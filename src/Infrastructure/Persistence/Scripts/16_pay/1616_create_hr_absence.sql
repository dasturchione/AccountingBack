create table hr_absence_type
(
    id smallint generated by default as identity not null,
    code varchar(50) not null,
    name varchar(200) not null,
    timesheet_category varchar(20) not null,
    is_paid boolean not null default false,
    state_id smallint not null default 1 references cmn_state(id),
    created_date timestamp without time zone not null default now(),
    constraint hr_absence_type_pkey primary key (id),
    constraint ux_hr_absence_type_code unique (code),
    constraint ck_hr_absence_type_category
        check (timesheet_category in ('LEAVE', 'SICK', 'ABSENT'))
);

