create table hr_absence
(
    id bigint generated by default as identity not null,
    organization_id integer not null references org_organization(id),
    employee_id bigint not null references pay_employee(id),
    absence_type_id smallint not null references hr_absence_type(id),
    doc_number varchar(100) not null,
    doc_date date not null,
    start_date date not null,
    end_date date not null,
    note varchar(1000),
    state_id smallint not null default 1 references cmn_state(id),
    created_date timestamp without time zone not null default now(),
    updated_date timestamp without time zone,
    created_by_user_id integer references sys_user(id),
    updated_by_user_id integer references sys_user(id),
    constraint hr_absence_pkey primary key (id),
    constraint ux_hr_absence_org_doc_number unique (organization_id, doc_number),
    constraint ck_hr_absence_dates check (end_date >= start_date)
);

create index idx_hr_absence_employee
    on hr_absence (organization_id, employee_id);

create index idx_hr_absence_dates
    on hr_absence (start_date, end_date);

create index idx_hr_absence_type
    on hr_absence (absence_type_id);

create table hr_absence_attachment
(
    id bigint generated by default as identity not null,
    organization_id integer not null references org_organization(id),
    absence_id bigint not null references hr_absence(id) on delete cascade,
    file_path varchar(500) not null,
    original_file_name varchar(255) not null,
    content_type varchar(150) not null,
    file_size bigint not null,
    telegram_file_id varchar(300) not null,
    telegram_message_id integer not null,
    created_date timestamp without time zone not null default now(),
    created_by_user_id integer references sys_user(id),
    constraint hr_absence_attachment_pkey primary key (id),
    constraint ck_hr_absence_attachment_size check (file_size > 0)
);

create index idx_hr_absence_attachment_organization
    on hr_absence_attachment (organization_id);

create index idx_hr_absence_attachment_absence
    on hr_absence_attachment (absence_id);
